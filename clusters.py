OTHER = ("misc", "Другие формулировки")
LEVELS = {"Проще ЕГЭ": 1, "Простая": 2, "Средняя": 3, "Сложная": 4, "Сложнее ЕГЭ": 5}
RANK_NAMES = {1: "очень лёгкое", 2: "лёгкое", 3: "среднее", 4: "сложное", 5: "очень сложное"}
_COMPILED = {n: [(k, lbl, re.compile(rx)) for k, lbl, rx in rules] for n, rules in RULES.items()}


def plain(h):
    t = re.sub(r"<[^>]+>", " ", h or "")
    return re.sub(r"\s+", " ", _html.unescape(t)).strip().lower().replace("ё", "е")


def labels(n):
    """Все типы номера по порядку: [(ключ, название)]."""
    return [(k, lbl) for k, lbl, _ in RULES.get(n, [])] + [OTHER]


def classify(t):
    """Ключ типа задания (без номера)."""
    n = t.get("n")
    topic = t.get("topic")
    if topic in TOPIC_MAP and TOPIC_MAP[topic][0] == n and TOPIC_MAP[topic][1]:
        return TOPIC_MAP[topic][1]
    txt = plain(t.get("html"))
    tail = txt[-450:]                 # вопрос — в конце условия: сначала ищем там
    for part in (tail, txt):
        for k, _, rx in _COMPILED.get(n, []):
            if rx.search(part):
                return k
    return OTHER[0]


def annotate(tasks):
    """Проставляет каждому заданию c (тип) и r (сложность 1–5). tasks — список заданий банка (меняются на месте)."""
    by = {}
    for t in tasks:
        t["c"] = classify(t)
        by.setdefault((t.get("n"), t["c"]), []).append(t)
    for group in by.values():
        lens = sorted(len(t.get("html") or "") for t in group)
        cut = lambda q: lens[min(len(lens) - 1, int(len(lens) * q))] if lens else 0
        lo, hi = cut(0.3), cut(0.75)
        for t in group:
            r = LEVELS.get(t.get("lv"))
            if r is None and t.get("d") in (1, 2, 3):
                r = t["d"] + 1
            if r is None:
                L = len(t.get("html") or "")
                r = 2 if L <= lo else 4 if L > hi else 3
            t["r"] = r
    return tasks


def catalog():
    """Справочник типов для страницы: {номер: [[ключ, название], …]}."""
    out = {n: [list(x) for x in labels(n)] for n in RULES}
    for n in range(1, 28):
        out.setdefault(n, [list(OTHER)])
    return out
