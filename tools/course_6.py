GEOM = '''from math import cos, sin, radians

def path(cmds, x=0, y=0, h=90):       # cmds: [('F', 24), ('R', 90), ...]; h = 90 — голова вверх
    pts = [(x, y)]
    for c, v in cmds:
        if c == 'F':
            x += v * cos(radians(h))
            y += v * sin(radians(h))
            pts.append((round(x, 6), round(y, 6)))
        else:
            h += -v if c == 'R' else v
    return pts[:-1]                    # последняя вершина совпала с первой

def on_edge(px, py, P):
    for (x1, y1), (x2, y2) in zip(P, P[1:] + P[:1]):
        cross = (x2 - x1) * (py - y1) - (y2 - y1) * (px - x1)
        if abs(cross) < 1e-6 and min(x1, x2) - 1e-6 <= px <= max(x1, x2) + 1e-6 \\
                and min(y1, y2) - 1e-6 <= py <= max(y1, y2) + 1e-6:
            return True
    return False

def inside(px, py, P):                 # луч вправо: нечётное число пересечений — внутри
    res = False
    for (x1, y1), (x2, y2) in zip(P, P[1:] + P[:1]):
        if (y1 > py) != (y2 > py) and px < x1 + (py - y1) * (x2 - x1) / (y2 - y1):
            res = not res
    return res
'''

