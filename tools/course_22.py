LOAD = '''from functools import lru_cache

T = {}
for s in open('FILE'):
    i, t, dep = s.strip().split('\\t')
    T[int(i)] = (int(t), [int(x) for x in dep.split(';') if int(x) != 0])

@lru_cache(None)
def end(i):                                # время окончания: максимум окончаний родителей + своё время
    t, d = T[i]
    return max([end(j) for j in d], default=0) + t

def works(i, ms):                          # идёт ли процесс i на миллисекунде ms
    return end(i) - T[i][0] + 1 <= ms <= end(i)
'''

