def mixed(count, lo, hi):
    """Числа разной длины: и двузначные, и трёх-, четырёх-, пятизначные, со знаком."""
    def gen(rng):
        out = []
        for _ in range(count):
            d = rng.choice([1, 2, 3, 3, 4, 4, 5])
            v = rng.randint(10 ** (d - 1), 10 ** d - 1)
            v = max(lo, min(hi, v * rng.choice([1, 1, -1])))
            out.append(str(v))
        return '\n'.join(out) + '\n'
    return gen


