def procs(n, tmax, maxdeps):
    """Процессы 1…n: время и зависимости (только от процессов с меньшими номерами — без циклов)."""
    def gen(rng):
        out = []
        for i in range(1, n + 1):
            k = rng.randint(0, min(maxdeps, i - 1))
            deps = sorted(rng.sample(range(1, i), k)) if k else []
            out.append(f"{i}\t{rng.randint(1, tmax)}\t{';'.join(map(str, deps)) if deps else '0'}")
        return '\n'.join(out) + '\n'
    return gen


