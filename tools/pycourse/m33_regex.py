def pattern_task(key, title, prompt, pattern, samples, hint, mode='finditer', stars=1):
    if mode == 'fullmatch':
        scan = """    match = regex.fullmatch(text)
    spans = [list(match.span())] if match else []"""
    else:
        group = 1 if mode == 'overlap' else 0
        scan = f'    spans = [list(m.span({group})) for m in regex.finditer(text)]'
    solution = f"""import re

regex = re.compile(r'{pattern}')
rows = []
for text in {samples!r}:
{scan}
    rows.append(spans)
print(rows)"""
    item = task(key, title, p(prompt), solution, hint=hint, stars=stars)
    item['regex'] = {'mode': mode, 'samples': samples}
    return item


