BUY = '''def purchase(goods, budget):
    prices_a = sorted(price for kind, price in goods if kind == 'A')
    prices_b = sorted(price for kind, price in goods if kind == 'B')
    def prefix(prices):
        sums = [0]
        for price in prices:
            sums.append(sums[-1] + price)
        return sums
    costs_a = prefix(prices_a)
    costs_b = prefix(prices_b)
    b = len(prices_b)
    best = (0, 0, budget)
    for a, cost_a in enumerate(costs_a):
        if cost_a > budget:
            break
        while cost_a + costs_b[b] > budget:
            b -= 1
        left = budget - cost_a - costs_b[b]
        best = max(best, (a + b, a, left))
    return best
'''

