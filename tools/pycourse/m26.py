def files_data(n, lo, hi, frac):
    def gen(rng):
        a = [rng.randint(lo, hi) for _ in range(n)]
        S = int(sum(a) * frac)
        return f'{S} {n}\n' + '\n'.join(map(str, a)) + '\n'
    return gen


def seats_data(rows, seats, busy):
    def gen(rng):
        occ = set()
        while len(occ) < busy:
            occ.add((rng.randint(1, rows), rng.randint(1, seats)))
        occ = list(occ)
        rng.shuffle(occ)
        return f'{len(occ)}\n' + '\n'.join(f'{r} {s}' for r, s in occ) + '\n'
    return gen


def intervals_data(n, T):
    def gen(rng):
        out = []
        for _ in range(n):
            a = rng.randint(0, T - 10)
            out.append((a, a + rng.randint(1, 120)))
        return f'{n}\n' + '\n'.join(f'{a} {b}' for a, b in out) + '\n'
    return gen


