def journal(rng):
    boundary = 12 * 3600
    times = rng.sample(range(7 * 3600, boundary - 2), 250) + rng.sample(range(boundary + 1, 18 * 3600), 227)
    events = [(t, rng.randrange(101, 130), 4 * rng.randint(1, 83)) for t in times]
    events += [(boundary - 2, 126, 503), (boundary - 1, 119, 4), (boundary, 107, 503)]
    rng.shuffle(events)
    lines = [f'{len(events)} 503']
    for t, client, size in events:
        lines.append(f'{t // 3600:02}:{t // 60 % 60:02}:{t % 60:02} {client} {size}')
    return '\n'.join(lines) + '\n'


