# Дополнительный навык: собственные учебные примеры, не перечень форматов КИМ.
FRAGMENT_SOLVER = '''from itertools import permutations

def valid_ipv4(address):
    octets = address.split('.')
    if len(octets) != 4:
        return False
    for part in octets:
        if not part or not all('0' <= c <= '9' for c in part):
            return False
        if len(part) > 1 and part[0] == '0':
            return False                         # условие запрещает ведущие нули
        if len(part) > 3 or int(part) > 255:
            return False
    return True

def restore(fragments):
    found = []
    for order in permutations(fragments):
        address = ''.join(fragments[label] for label in order)
        if valid_ipv4(address):
            found.append((''.join(order), address))
    return found
'''

