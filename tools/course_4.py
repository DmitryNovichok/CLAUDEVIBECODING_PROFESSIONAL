HEAD = '''from itertools import product

words = [''.join(t) for n in range(1, 5) for t in product('01', repeat=n)]   # все слова длиной 1–4

def fano(c):                     # ни одно слово не является началом другого
    c = list(c)
    return len(set(c)) == len(c) and all(not b.startswith(a) for a in c for b in c if a != b)
'''

L.code('demo', HEAD + '''
known = {'Б': '00', 'Н': '010', 'Л': '111'}
word = 'КОЛОБОК'
best = 10 ** 9
for k, o in product(words, repeat=2):
    c = dict(known, К=k, О=o)
    if fano(c.values()):
        best = min(best, sum(len(c[ch]) for ch in word))
print(best)
''', want='17')

