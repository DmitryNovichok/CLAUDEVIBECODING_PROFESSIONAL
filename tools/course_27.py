def blobs(spec):
    pts = []
    for label, (cx, cy, sd, n) in enumerate(spec):
        for _ in range(n):
            pts.append((round(R.gauss(cx, sd), 4), round(R.gauss(cy, sd), 4), label))
    R.shuffle(pts)
    return pts


