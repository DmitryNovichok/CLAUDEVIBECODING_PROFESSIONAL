def _centers(pts, k):
    out = []
    for lab in range(k):
        c = [(x, y) for x, y, l in pts if l == lab]
        out.append(min(c, key=lambda a: sum(math.dist(a, b) for b in c)))
    return out


def _pxy(pts, k):
    cs = _centers(pts, k)
    return int(sum(x for x, y in cs) / k * 10000), int(sum(y for x, y in cs) / k * 10000)


