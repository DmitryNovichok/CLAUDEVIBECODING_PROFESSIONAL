book = json.load(gzip.open(Path(__file__).parent / 'books10' / 'duel.json.gz', 'rt', encoding='utf-8'))
MARK = re.compile('(\\d+)')
units = book['units'][:3]
lines = ['Александр Куприн', 'Поединок (главы I–III)', '']
refs = []
for u in units:
    lines.append(f"Глава {u['label']}")
    for p in u['paras']:
        refs += MARK.findall(p)
        lines.append(MARK.sub(lambda m: f'[{m.group(1)}]', p))
if refs:
    lines.append('Примечания')
    lines += [f'[{r}] {book["notes"][int(r) - 1]}' for r in dict.fromkeys(refs)]
L.file('10.txt', '\n'.join(lines) + '\n')

