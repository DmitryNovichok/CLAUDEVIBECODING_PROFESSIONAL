# ---- независимая проверка
def _arch():
    a = sorted(A)
    k = 0
    while sum(a[:k + 1]) <= A_S and k < len(a):
        k += 1
    best = max(x for x in set(a) if sum(a[:k - 1]) + x <= A_S and (x >= a[k - 1]))
    return k, best


assert tuple(map(int, L.ans('arch').split())) == _arch() and _arch()[0] < A_N


def _chain(vals, gap, down):
    """Самая длинная цепочка с шагом не меньше gap (динамика по различным значениям) и лучший крайний элемент."""
    u = sorted(set(vals), reverse=down)
    dp = {}
    for i, x in enumerate(u):
        dp[x] = 1 + max([dp[y] for y in u[:i] if abs(x - y) >= gap], default=0)
    m = max(dp.values())
    ends = [x for x in u if dp[x] == m]
    return m, (max(ends) if down else min(ends))


