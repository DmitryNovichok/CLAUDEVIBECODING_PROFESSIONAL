def picked(f, what, total=True):
    """Строки после фильтров и вычисление ответа. what: mass | money | change."""
    rs = list(rows(f))
    head = "<th>ID</th><th>Дата</th><th>Магазин</th><th>Товар</th><th>Тип</th><th>Упак.</th>"
    if what == "mass":
        head += '<th class="add">В упак.</th><th class="add">Итог</th>'
        val = lambda r: r["k"] * r["per"]
        term = lambda r: f"{r['k']}×{num(r['per'])}"
    elif what == "money":
        head += '<th>Цена</th><th class="add">Итог</th>'
        val = lambda r: r["k"] * r["price"]
        term = lambda r: f"{r['k']}×{r['price']}"
    elif what == "count":
        val = lambda r: r["k"]
        term = None
    else:
        head += '<th class="add">±</th>'
        val = lambda r: r["k"] if r["typ"] == "Поступление" else -r["k"]
        term = lambda r: f"{val(r)}"
    body = ""
    for r in rs:
        extra = (f'<td class="add">{num(r["per"])}</td>' if what == "mass" else f"<td>{r['price']}</td>" if what == "money" else "")
        body += (f"<tr><td>{r['id']}</td><td>{r['d']:02d}.06</td><td>{r['shop']}</td><td>{r['name']}</td><td>{r['typ']}</td>"
                 f"<td>{r['k']}</td>{extra}" + (f'<td class="add">{num(val(r))}</td>' if what != "count" else "") + "</tr>")
    table = f'<table class="sl-tab sl-db sl-moves"><tr>{head}</tr>{body}</table>'
    if not total or term is None:
        return table
    expr = " + ".join(term(r) for r in rs).replace("+ -", "− ").replace("-", "−")
    return table + f'<p class="calc">{expr} = <b>{num(sum(val(r) for r in rs)).replace("-", "−")}</b></p>'


