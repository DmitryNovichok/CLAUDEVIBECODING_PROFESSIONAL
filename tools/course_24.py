# ---- независимая проверка другими способами
def _longest(text, ok):
    """Самая длинная подстрока, где для каждой соседней пары выполняется ok(левый, правый)."""
    best = cur = 1
    for i in range(1, len(text)):
        cur = cur + 1 if ok(text[i - 1], text[i]) else 1
        best = max(best, cur)
    return best


def _window(text, chars, k):
    """Самая длинная подстрока, где символов из chars не более k — через список позиций."""
    best, pos = 0, [-1] + [i for i, c in enumerate(text) if c in chars] + [len(text)]
    for i in range(len(pos) - k - 1):
        best = max(best, pos[i + k + 1] - pos[i] - 1)
    return best


