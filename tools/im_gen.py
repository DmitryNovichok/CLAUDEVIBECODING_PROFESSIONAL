def gen_dist():
    while True:
        ps = [Fraction(R.randint(1, 8), 20) for _ in range(5)]
        if sum(ps) == 1:
            break
    miss = R.randint(1, 4)
    m = sum(Fraction(i) * ps[i] for i in range(5))
    n_good = R.choice([200, 300, 400, 500, 600, 800])
    k = m * n_good
    if k.denominator != 1:
        return gen_dist()
    k = int(k)
    m_wrong = sum(Fraction(i) * ps[i] for i in range(5) if i != miss)
    cands = {round(k / 4), int(k / m_wrong) if m_wrong else k + 1, k, round(k / 2)}
    cands = {c for c in cands if c != n_good and c > 0}
    while len(cands) < 3:
        cands.add(n_good + R.choice([-100, 100, 50]))
    opts, kk = shuffle_with(n_good, R.sample(sorted(cands), 3))
    cells = "".join(f"<td>{'?' if i == miss else num(float(ps[i]))}</td>" for i in range(5))
    what = R.choice([("Нейросеть расшифровывает аудиозаписи лекций", "ошибок распознавания за минуту записи", "минут", "исправить"),
                     ("Робот сортирует посылки на складе", "ошибок сортировки за час работы", "часов", "перепроверить"),
                     ("Сервис машинного перевода обрабатывает тексты", "ошибок на страницу", "страниц", "исправить")])
    html = p(f"{what[0]}. Число {what[1]} — случайная величина X. Её закон распределения:") + \
        f"<table class=\"im-tt\"><tr><th>X</th>{''.join(f'<th>{i}</th>' for i in range(5))}</tr><tr><th>P</th>{cells}</tr></table>" + \
        p(f"Одно значение стёрлось. Редактор может {what[3]} {k} ошибок. Какой объём ({what[2]}) он успеет полностью обработать, "
          "если ориентироваться на ожидаемое число ошибок?") + options([str(o) for o in opts], True)
    assert sum(Fraction(i) * ps[i] for i in range(5)) * n_good == k
    sol = p(f"Пропуск: P(X={miss}) = 1 − (сумма остальных) = {num(float(ps[miss]))}.",
            "M(X) = " + " + ".join(f"{i}·{num(float(ps[i]))}" for i in range(5)) + f" = {num(float(m))}.",
            f"По закону больших чисел за N единиц ожидается M(X)·N ошибок: {num(float(m))} · N = {k} ⇒ N = {n_good}.")
    return {"kind": "choice", "html": html, "ans": str(kk), "sol": sol, "val": str(n_good)}


# ============================================================== 5. Идеальный газ: изопроцессы по графику (физика, Б2, 5 баллов)
def gas_svg(T, P, labels=("T", "p")):
    """p–T график: точки 1, 2, 3; 1–2 лежит на прямой из начала координат (изохора), 2–3 горизонталь (изобара)."""
    W, H = 260, 150
    mx, my = max(T) * 1.15, max(P) * 1.25
    X = lambda t: 24 + t / mx * (W - 40)
    Y = lambda pp: H - 20 - pp / my * (H - 40)
    pts = list(zip(T, P))
    s = [f'<svg class="im-fig" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="график процесса">',
         f'<path d="M24 {H - 20}H{W - 6}M24 {H - 20}V8" stroke="currentColor" fill="none"/>',
         f'<path d="M{W - 12} {H - 24}l6 4-6 4M20 14l4-6 4 6" stroke="currentColor" fill="none"/>',
         f'<text x="{W - 14}" y="{H - 4}" font-size="11">{labels[0]}</text><text x="6" y="14" font-size="11">{labels[1]}</text>',
         f'<text x="16" y="{H - 6}" font-size="10">0</text>',
         f'<path d="M24 {H - 20}L{X(T[0]):.1f} {Y(P[0]):.1f}" stroke="currentColor" stroke-dasharray="3 3" fill="none"/>',
         f'<path d="M{X(T[0]):.1f} {Y(P[0]):.1f}L{X(T[1]):.1f} {Y(P[1]):.1f}L{X(T[2]):.1f} {Y(P[2]):.1f}" stroke="currentColor" stroke-width="1.6" fill="none"/>']
    for i, (t, pp) in enumerate(pts):
        s.append(f'<circle cx="{X(t):.1f}" cy="{Y(pp):.1f}" r="3"/><text x="{X(t) - 3:.1f}" y="{Y(pp) - 7:.1f}" font-size="11">{i + 1}</text>')
    s.append("</svg>")
    return "".join(s)


