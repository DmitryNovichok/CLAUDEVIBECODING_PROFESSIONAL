def fmt_power(w):
    return f"{num(round(w, 3))} Вт" if w >= 1 else f"{num(round(w * 1000, 1))} мВт"


def gen_ohm():
    while True:
        U = R.choice([5, 9, 12, 15, 24])
        I = R.choice([10, 15, 20, 25, 30]) / 1000
        series = R.sample([100, 150, 220, 330, 470, 560, 680, 820, 1000, 1200, 1500, 2200], 4)
        series.sort()
        need = U / I
        ok = [r for r in series if r >= need]
        if ok and ok[0] != series[0] and abs(ok[0] - need) > 1e-9:
            break
    Rg = ok[0]
    P = U * U / Rg
    wrong = [U * I, U * U / series[0], I * I * Rg, U * U / series[-1] if series[-1] != Rg else U * U / (Rg * 2)]
    texts, seen = [], {fmt_power(P)}
    for w in wrong:
        t = fmt_power(w)
        if t not in seen:
            seen.add(t)
            texts.append(t)
    while len(texts) < 4:
        t = fmt_power(P * R.choice([1.5, 0.5, 2.2, 0.3]))
        if t not in seen:
            seen.add(t)
            texts.append(t)
    opts, k = shuffle_with(fmt_power(P), texts[:4])
    # проверка перебором: из резисторов, где ток не больше допустимого, — с наименьшим тепловыделением? нет: условие —
    # ток не больше I, а из подходящих — тот, где потери минимальны при соблюдении условия (наибольший ток — ближайший номинал)
    feasible = [r for r in series if U / r <= I + 1e-12]
    assert min(feasible) == Rg
    html = p(f"Есть источник напряжением {U} В и электронный модуль, которому нужен постоянный ток не более {num(I * 1000)} мА. "
             f"Для защиты модуля последовательно в цепь питания ставят резистор. В наличии номиналы: "
             f"{', '.join((f'{r // 1000} кОм' if r % 1000 == 0 else f'{num(r / 1000)} кОм') if r >= 1000 else f'{r} Ом' for r in series)}.",
             "Какую мощность будет выделять резистор, если выбрать из подходящих номинал, ближайший к расчётному "
             "(сопротивлением модуля пренебречь)? Запишите номер верного ответа.") + options(opts)
    sol = p(f"Наименьшее допустимое сопротивление: R = U / I = {U} / {num(I)} = {num(round(need, 2))} Ом. "
            f"Подходят номиналы не меньше него, ближайший — {Rg} Ом.",
            f"Ток: I = {U} / {Rg} = {num(round(U / Rg, 5))} А. Мощность: P = U²/R = {U}² / {Rg} = {fmt_power(P)} — вариант {k}.")
    return {"kind": "choice", "html": html, "ans": str(k), "sol": sol}


