def gen_gas():
    p1 = R.choice([60, 80, 100, 120, 150, 200])
    k = R.choice([2, 3, 4])
    T1 = 100
    T2 = T1 * k
    up = R.random() < 0.6                         # на участке 2–3 температура растёт или падает
    T3 = T2 * (1.6 if up else 0.55)
    p2 = p1 * k
    P = [p1, p2, p2]
    T = [T1, T2, T3]
    # концентрация n = p / (k_B T): изобара, T растёт → n падает
    n2, n3 = p2 / T2, p2 / T3
    rel_ok = 2 if n3 < n2 else 3
    wrong_p = sorted({p1, p1 // k if p1 % k == 0 else p1 + 40, p1 * (k + 1), p1 * k * 2, p1 + k * 10} - {p2})
    vals = list(set(R.sample(wrong_p, min(4, len(wrong_p)))) | {p2})
    extra = [p2 + 20, p2 + 40, p2 * 2, p2 + 60]
    while len(vals) < 5:
        vals.append(next(x for x in extra if x not in vals))
    vals = vals[:5]
    R.shuffle(vals)
    i_p = vals.index(p2) + 1
    assert abs(p1 / T1 - p2 / T2) < 1e-9 and (n3 < n2) == up
    html = p("На рисунке — график изменения состояния идеального одноатомного газа постоянной массы в системе охлаждения сервера. "
             f"Газ переходит из состояния 1 в состояние 2, затем в состояние 3. В состоянии 1 давление газа {p1} кПа. "
             f"При переходе 1 → 2 температура увеличилась в {k} раза.") + gas_svg(T, P) + \
        p("1. Найдите давление газа в состоянии 3. 2. Сравните концентрацию молекул в состояниях 2 и 3.",
          "Запишите ответ двумя цифрами через запятую — номера верных ответов (сначала давление, затем сравнение).") + \
        "<div class=\"im-two\">" + options([f"{v} кПа" for v in vals]) + options(REL) + "</div>"
    sol = p(f"Участок 1–2 лежит на прямой, проходящей через начало координат p–T, — это изохора: p/T = const ⇒ p₂ = {k} · {p1} = {p2} кПа.",
            f"Участок 2–3 горизонтальный — изобара: p₃ = p₂ = {p2} кПа (вариант {i_p}).",
            f"При p = const концентрация n = p/(kT) обратно пропорциональна T. Температура {'растёт' if up else 'падает'} ⇒ "
            f"n₃ {'&lt;' if up else '&gt;'} n₂ (вариант {rel_ok}).")
    return {"kind": "pair", "html": html, "ans": f"{i_p}, {rel_ok}", "sol": sol}


