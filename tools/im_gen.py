def gen_calc():
    while True:
        r1 = R.randint(2, 10)
        r2 = r1 + 2 * R.randint(1, 4)             # r1 + r2 чётно — коэффициенты целые
        a2, a1 = -3 * (r1 + r2) // 2, 3 * r1 * r2
        c0 = R.choice([100, 200, 300, 400, 500])
        L = R.randint(max(0, r1 - 6), r1 - 1)
        Rr = R.randint(r2 + 1, r2 + 6)
        C = lambda x: x ** 3 + a2 * x ** 2 + a1 * x + c0
        want = R.choice(["min", "max"])
        vals = {L: C(L), r1: C(r1), r2: C(r2), Rr: C(Rr)}
        best = min(vals.values()) if want == "min" else max(vals.values())
        # проверка: значения на частой сетке не лучше найденного
        grid = [C(L + (Rr - L) * i / 4000) for i in range(4001)]
        if want == "min":
            assert min(grid) >= best - 1e-6
        else:
            assert max(grid) <= best + 1e-6
        if best > 0 and len(set(vals.values())) == 4:
            break
    v0, kk, T = R.choice([(300, 12, 10), (200, 8, 10), (240, 6, 20), (500, 20, 10), (180, 6, 15), (400, 16, 12)])
    S = v0 * T - kk * T * T // 2 if kk * T * T % 2 == 0 else None
    if S is None or S <= 0:
        return gen_calc()
    assert abs(sum((v0 - kk * (i + 0.5) * T / 10000) * T / 10000 for i in range(10000)) - S) < 1e-6
    poly = f"x³ − {-a2}x² + {a1}x + {c0}"
    html = p("В вычислительном кластере планируется обучение нейросетевой модели.",
             f"<b>Часть А.</b> Стоимость запуска (усл. ед.) зависит от числа узлов x: C(x) = {poly}. Число узлов может меняться "
             f"от {L} до {Rr} включительно. Найдите {'наименьшую' if want == 'min' else 'наибольшую'} возможную стоимость на этом отрезке.",
             f"<b>Часть Б.</b> Скорость обработки примеров v(t) = {v0} − {kk}t (тыс. примеров в минуту, t — минуты от начала). "
             f"Сколько тысяч примеров будет обработано за первые {T} минут?",
             "Запишите два числа через точку с запятой: сначала ответ части А, затем части Б.")
    sol = p(f"А. C′(x) = 3x² − {-2 * a2}x + {a1} = 3(x − {r1})(x − {r2}). На [{L}; {Rr}]: x = {r1} — максимум, x = {r2} — минимум.",
            "Значения: " + ", ".join(f"C({x}) = {y}" for x, y in vals.items()) +
            f". {'Наименьшее' if want == 'min' else 'Наибольшее'} — {best} (обязательно сравнить с концами отрезка).",
            f"Б. ∫₀<sup>{T}</sup> ({v0} − {kk}t) dt = [{v0}t − {kk // 2 if kk % 2 == 0 else num(kk / 2)}t²]₀<sup>{T}</sup> = {S}.",
            f"Ответ: {best}; {S}.")
    return {"kind": "pair", "html": html, "ans": f"{best}; {S}", "sol": sol}


