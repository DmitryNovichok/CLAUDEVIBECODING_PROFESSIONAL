def num(x):
    """Число по-русски: запятая, без лишних нулей."""
    if isinstance(x, Fraction):
        x = float(x)
    if isinstance(x, float) and x.is_integer():
        x = int(x)
    return str(x).replace(".", ",")


def shuffle_with(correct, wrong):
    """Варианты вперемешку; возвращает (список, номер верного с 1)."""
    opts = [correct] + wrong
    R.shuffle(opts)
    return opts, opts.index(correct) + 1


# ============================================================== 1. IP-адреса и подсети (информатика, Б1, 3 балла)
def ip_same(a, b, prefix):
    m = (0xFFFFFFFF << (32 - prefix)) & 0xFFFFFFFF if prefix else 0
    return (a & m) == (b & m)


def ip(x):
    return ".".join(str((x >> s) & 255) for s in (24, 16, 8, 0))


def gen_ip():
    base = (R.choice([10, 172, 192]) << 24) | (R.choice([0, 1, 16, 168, 200]) << 16) | (R.randrange(256) << 8)
    while True:
        a, b = sorted(R.sample(range(1, 255), 2))
        d = (a ^ b).bit_length()                 # различаются в младших d битах
        if 2 <= d <= 6:
            break
    lo = a >> d << d
    hi = lo + (1 << d) - 1
    inside = [x for x in range(lo, hi + 1) if x not in (a, b)]
    outside = [x for x in range(1, 255) if not lo <= x <= hi]
    good = R.choice(inside)
    wrong = R.sample(outside, 3)
    opts, k = shuffle_with(good, wrong)
    A, B = base | a, base | b
    # проверка: «гарантированно» = в той же подсети при любой маске, при которой A и B в одной подсети
    masks = [pfx for pfx in range(33) if ip_same(A, B, pfx)]
    ok = [all(ip_same(A, base | o, pfx) for pfx in masks) for o in opts]
    assert ok.count(True) == 1 and ok.index(True) == k - 1
    html = p(f"На сетевом узле зарегистрированы два IP-адреса компьютеров, которые находятся в одной и той же подсети: "
             f"<b>{ip(A)}</b> и <b>{ip(B)}</b>.",
             "Укажите номер IP-адреса, который <b>гарантированно</b> также находится в этой же подсети.") + \
        options([ip(base | o) for o in opts])
    bits = lambda x: f"{x:08b}"
    sol = p(f"Последние байты: {a} = {bits(a)}, {b} = {bits(b)}. Они различаются в младших {d} битах — там в маске обязаны быть нули, "
            f"а маска — сплошные единицы слева, поэтому самая строгая маска в последнем байте — {bits((255 << d) & 255)} "
            f"({(255 << d) & 255}).",
            f"Сетевой адрес при самой строгой маске: {a} AND {(255 << d) & 255} = {lo}. Гарантированно в этой подсети только адреса "
            f"с последним байтом от {lo} до {hi}. Подходит {ip(base | good)} — ответ {k}.")
    return {"kind": "choice", "html": html, "ans": str(k), "sol": sol}


# ============================================================== 2. Логика: КНФ по таблице истинности (информатика, Б3, 6 баллов)
def lit(v, neg):
    return f"<span class=\"ov\">{v}</span>" if neg else v


def clause_html(cl):
    return "(" + " ∨ ".join(lit(v, n) for v, n in cl) + ")"


def cnf_html(cnf):
    return " ∧ ".join(clause_html(c) for c in cnf)


def cnf_eval(cnf, env):
    return all(any(env[v] != n for v, n in cl) for cl in cnf)


def gen_logic():
    names = R.choice([("A", "B"), ("X", "Y"), ("A", "B", "C")])
    rows = list(itertools.product([0, 1], repeat=len(names)))
    while True:
        f = [R.randint(0, 1) for _ in rows]
        if 0 < sum(f) < len(f) and (len(names) == 2 or 2 <= f.count(0) <= 3):
            break
    # верная КНФ: по строкам, где F = 0
    cnf = [[(v, val == 1) for v, val in zip(names, r)] for r, fv in zip(rows, f) if fv == 0]
    if len(names) == 2 and len(cnf) == 1:
        cnf = cnf + [cnf[0][::-1]]               # две скобки, как в задании: (A∨B)∧(B∨A) — та же функция
    good = cnf
    wrong, seen = [], {tuple(f)}
    tries = 0
    while len(wrong) < 3 and tries < 500:
        tries += 1
        w = [[(v, R.random() < 0.5) for v in names] for _ in range(len(good))]
        tt = tuple(int(cnf_eval(w, dict(zip(names, r)))) for r in rows)
        if tt not in seen:
            seen.add(tt)
            wrong.append(w)
    assert len(wrong) == 3
    opts, k = shuffle_with(good, wrong)
    for i, o in enumerate(opts):
        tt = [int(cnf_eval(o, dict(zip(names, r)))) for r in rows]
        assert (tt == f) == (i == k - 1)
    sys_name = R.choice(["Система аварийного оповещения на станции «Вега-3»", "Охранная сигнализация серверной",
                         "Контроллер умной теплицы", "Модуль блокировки двери лаборатории", "Система полива школьного сада"])
    table = "<table class=\"im-tt\"><tr>" + "".join(f"<th>{v}</th>" for v in names) + "<th>F</th></tr>" + \
        "".join("<tr>" + "".join(f"<td>{x}</td>" for x in r) + f"<td>{fv}</td></tr>" for r, fv in zip(rows, f)) + "</table>"
    html = p(f"{sys_name} управляется сигналами {', '.join(names)}. Функция F описывает её срабатывание (F = 1). "
             "По журналу срабатываний составлена таблица:") + table + \
        p("Какое из выражений (в конъюнктивной форме) корректно описывает работу системы? Черта над буквой — отрицание.") + \
        options([f"F = {cnf_html(o)}" for o in opts])
    zero = [r for r, fv in zip(rows, f) if fv == 0]
    sol = p("КНФ строится по строкам, где F = 0: для каждой такой строки — скобка-дизъюнкция, в которой переменная, равная 1, "
            "берётся с отрицанием, а равная 0 — без него. Строки с F = 0: " +
            "; ".join(", ".join(f"{v}={x}" for v, x in zip(names, r)) for r in zero) + ".",
            f"Получаем F = {cnf_html(good)} — это вариант {k}. Проверка: подставьте каждую строку таблицы.")
    return {"kind": "choice", "html": html, "ans": str(k), "sol": sol}


