def gen_exp():
    q = R.choice([2, 2, 3])
    t1 = R.choice([2, 3, 4, 5])
    t2 = t1 + R.choice([2, 3, 4]) if q == 2 else t1 + R.choice([1, 2])
    n0 = R.choice([3, 5, 6, 12, 15, 24]) if q == 2 else R.choice([2, 4, 5, 7])
    n1, n2 = n0 * q ** t1, n0 * q ** t2
    what = R.choice([("Обучающий набор системы распознавания речи", "тыс. записей"),
                     ("Число пользователей нового школьного сервиса", "сотен человек"),
                     ("Объём журналов сервера", "ГБ"), ("Число узлов в тестовой сети", "штук")])
    wrong = sorted({t2 - 1, t2 + 2, t1 * 2 if t1 * 2 != t2 else t2 + 3, t2 + 1} - {t2})
    opts, k = shuffle_with(t2, R.sample(wrong, 3))
    sol_t = next(t for t in range(0, 40) if n0 * q ** t == n2)
    assert sol_t == t2 and n0 * q ** t1 == n1
    html = p(f"{what[0]} растёт по модели N(t) = N₀ · qᵗ, где N — объём ({what[1]}), t — число месяцев от начала наблюдений, "
             f"q — постоянный множитель прироста за месяц (q &gt; 1). В начале было {n0} {what[1]}, а через {t1} мес. — {n1} {what[1]}.",
             f"Через сколько месяцев от начала объём достигнет {n2} {what[1]}?") + options([str(o) for o in opts], True)
    sol = p(f"N₀ = {n0}. Через {t1} мес.: {n0} · q<sup>{t1}</sup> = {n1} ⇒ q<sup>{t1}</sup> = {n1 // n0} ⇒ q = {q}.",
            f"{n0} · {q}ᵗ = {n2} ⇒ {q}ᵗ = {n2 // n0} = {q}<sup>{t2}</sup> ⇒ t = {t2}.")
    return {"kind": "choice", "html": html, "ans": str(k), "sol": sol, "val": str(t2)}


