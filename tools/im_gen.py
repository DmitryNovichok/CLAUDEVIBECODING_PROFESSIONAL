# ============================================================== 9. Полная вероятность, Байес, Бернулли (математика, П1, 7 баллов)
def gen_bayes():
    while True:
        pm = R.choice([0.02, 0.03, 0.04, 0.05, 0.1])
        pam = R.choice([0.8, 0.85, 0.9, 0.95])
        pal = R.choice([0.02, 0.03, 0.04, 0.05])
        n = R.choice([3, 4, 5])
        k = R.randint(1, n - 1)
        pa = pm * pam + (1 - pm) * pal
        q = pm * pam / pa
        v = math.comb(n, k) * q ** k * (1 - q) ** (n - k)
        frac = v * 100 - math.floor(v * 100)
        q2 = round(q, 2)
        v2 = math.comb(n, k) * q2 ** k * (1 - q2) ** (n - k)
        if 0.08 < frac < 0.42 or 0.58 < frac < 0.92:
            if round(v, 2) == round(v2, 2) and 0.02 <= v <= 0.98:
                break
    ans = f"{round(v, 2):.2f}".replace(".", ",")
    # проверка моделированием дробями
    qf = Fraction(str(pm)) * Fraction(str(pam)) / (Fraction(str(pm)) * Fraction(str(pam)) + (1 - Fraction(str(pm))) * Fraction(str(pal)))
    vf = math.comb(n, k) * qf ** k * (1 - qf) ** (n - k)
    assert f"{round(float(vf), 2):.2f}".replace(".", ",") == ans
    ctx = R.choice([("платёжном сервисе", "мошеннические транзакции", "транзакций", "мошеннической"),
                    ("почтовом сервисе", "письма со спамом", "писем", "спамом"),
                    ("системе видеонаблюдения", "кадры с нарушителем", "кадров", "с нарушителем")])
    html = p(f"В {ctx[0]} {num(round(pm * 100, 1))}% всех объектов — {ctx[1]}. Модель машинного обучения помечает часть {ctx[2]} как подозрительные:") + \
        f"<table class=\"im-tt\"><tr><th>Характеристика модели</th><th>Значение</th></tr><tr><td>Пометить «плохой» объект</td><td>{num(pam)}</td></tr>" \
        f"<tr><td>Пометить «хороший» объект</td><td>{num(pal)}</td></tr></table>" + \
        p(f"Независимо отобраны {n} помеченных {ctx[2]}. Найдите вероятность того, что ровно {k} из них действительно "
          f"{'окажется' if k == 1 else 'окажутся'} «плохими». Ответ округлите до сотых.")
    sol = p(f"Полная вероятность пометки: P(A) = {num(pm)}·{num(pam)} + {num(round(1 - pm, 3))}·{num(pal)} = {num(round(pa, 5))}.",
            f"По формуле Байеса P(плохой | помечен) = {num(round(pm * pam, 5))} / {num(round(pa, 5))} ≈ {num(round(q, 4))}.",
            f"Схема Бернулли: C({n},{k}) · p<sup>{k}</sup> · (1 − p)<sup>{n - k}</sup> ≈ {num(round(v, 4))} ≈ {ans}.")
    return {"kind": "num", "html": html, "ans": ans, "sol": sol}


