def solve_slide(cond, sol, ans, note, h, k, kc="t1", nk="secret", ch="Задание"):
    """Реши сам: условие, а решение по шагам и ответ — по кнопкам."""
    return {"t": "solve", "k": k, "kc": kc, "h": h, "ch": ch, "cond": cond, "sol": sol, "ans": str(ans), "note": note, "nk": nk, "stack": True}


def ol(*items):
    return "<ol>" + "".join(f"<li>{x}</li>" for x in items) + "</ol>"


def n(task, k):
    """Номер пункта в таблице: «П3»."""
    return f"П{task.secret[k]}"


def path(task, *ks):
    """Маршрут по буквам и его длина: «А–Б–Г = 4 + 2 + 11 = 17»."""
    ws = [task.w["".join(sorted(ks[i:i + 2], key=task.letters.index))] for i in range(len(ks) - 1)]
    return f"{'–'.join(ks)} = {' + '.join(map(str, ws))} = <b>{sum(ws)}</b>"


