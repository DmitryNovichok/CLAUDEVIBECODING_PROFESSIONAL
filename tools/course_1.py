# ---------------------------------------------------------------- задача: схема + таблица
class Task:
    def __init__(self, pos, edges, secret, weights=None):
        """pos: буква → (x, y) на рисунке; edges: 'АБ АВ …'; secret: буква → номер в таблице;
        weights: 'АБ' → длина (None — таблица со звёздочками)."""
        self.pos = pos
        self.edges = edges.split()
        self.secret = secret
        self.w = weights
        self.letters = sorted(pos)
        self.n = len(self.letters)
        self.table = {}
        for e in self.edges:
            a, b = sorted((secret[e[0]], secret[e[1]]))
            self.table[(a, b)] = weights[e] if weights else "*"

    def cell(self, i, j):
        return self.table.get((min(i, j), max(i, j)), "")

    def mappings(self):
        """Все соответствия букв номерам, при которых схема совпадает с таблицей."""
        out = []
        for p in permutations(range(1, self.n + 1)):
            num = dict(zip(self.letters, p))
            if all(self.cell(num[e[0]], num[e[1]]) != "" for e in self.edges):
                out.append(num)
        return out

    def road(self, num, a, b):
        return self.cell(num[a], num[b])

    def shortest(self, num, a, b):
        """Кратчайший путь по таблице между пунктами a и b (буквы схемы)."""
        dist, q = {num[a]: 0}, [(0, num[a])]
        while q:
            d, v = heapq.heappop(q)
            if v == num[b]:
                return d
            if d > dist.get(v, 1e9):
                continue
            for u in range(1, self.n + 1):
                c = self.cell(v, u)
                if c != "" and d + c < dist.get(u, 1e9):
                    dist[u] = d + c
                    heapq.heappush(q, (d + c, u))
        return None

    def answer(self, f):
        """Ответ, одинаковый при всех подходящих соответствиях, — иначе ошибка генератора."""
        res = {f(m) for m in self.mappings()}
        assert len(res) == 1, f"неоднозначный ответ: {res}"
        return res.pop()

    # ---------- картинки
    def svg(self, hl=(), w=250, h=190):
        xs = [x for x, _ in self.pos.values()]
        ys = [y for _, y in self.pos.values()]
        sx = lambda x: 22 + (x - min(xs)) / ((max(xs) - min(xs)) or 1) * (w - 44)
        sy = lambda y: 22 + (y - min(ys)) / ((max(ys) - min(ys)) or 1) * (h - 44)
        lines = "".join(
            f'<line x1="{sx(self.pos[e[0]][0]):.0f}" y1="{sy(self.pos[e[0]][1]):.0f}" x2="{sx(self.pos[e[1]][0]):.0f}" '
            f'y2="{sy(self.pos[e[1]][1]):.0f}" class="{"hl" if e in hl or e[::-1] in hl else ""}"/>' for e in self.edges)
        nodes = "".join(f'<g><circle cx="{sx(x):.0f}" cy="{sy(y):.0f}" r="14"/><text x="{sx(x):.0f}" y="{sy(y) + 5:.0f}">{k}</text></g>'
                        for k, (x, y) in sorted(self.pos.items()))
        return f'<svg class="sl-graph" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="схема дорог">{lines}{nodes}</svg>'

    def html_table(self, cls=""):
        head = "".join(f"<th>П{j}</th>" for j in range(1, self.n + 1))
        rows = "".join(f"<tr><th>П{i}</th>" + "".join(
            f'<td class="{"x" if i == j else ""}">{self.cell(i, j)}</td>' for j in range(1, self.n + 1)) + "</tr>"
            for i in range(1, self.n + 1))
        return f'<table class="sl-tab sl-adj {cls}"><tr><th></th>{head}</tr>{rows}</table>'

    def degrees(self):
        g = {k: sum(k in e for e in self.edges) for k in self.letters}
        t = {i: sum(1 for j in range(1, self.n + 1) if self.cell(i, j) != "") for i in range(1, self.n + 1)}
        return g, t


