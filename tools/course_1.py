def pair(task, extra=""):
    """Схема и таблица рядом."""
    return f'<div class="sl-pair">{task.svg()}{task.html_table()}</div>{extra}'


def degs(task):
    g, t = task.degrees()
    gs = " · ".join(f"{k}<sub>{v}</sub>" for k, v in g.items())
    ts = " · ".join(f"П{k}<sub>{v}</sub>" for k, v in t.items())
    return f'<p class="sl-degs"><b>Схема:</b> {gs}<br><b>Таблица:</b> {ts}</p>'


