# ---- независимая проверка: наивный перебор делителей
def _divs(n):
    return [d for d in range(1, n + 1) if n % d == 0]


rows = [list(map(int, r.split())) for r in L.ans('m').split('\n')]
assert len(rows) == 5 and all(700000 < n and _divs(n)[1] + _divs(n)[-2] == m and m % 10 == 8 for n, m in rows)
