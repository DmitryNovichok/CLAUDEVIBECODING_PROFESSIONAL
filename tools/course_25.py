assert all(n % 1917 == 0 and fnmatch(str(n), '12*4?5') for n, q in rows) and 1 <= len(rows) <= 11
rows = [list(map(int, r.split())) for r in L.ans('p3').split('\n')]
assert len(rows) == 5 and all(len([d for d in _divs(n) if d % 2 == 0]) == 3 and [d for d in _divs(n) if d % 2 == 0][-2] == x for n, x in rows)

