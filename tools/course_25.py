assert [n for k, n in rows] == [n for n in range(2532000, 2532161) if len(_divs(n)) == 2] and 4 <= len(rows) <= 11
rows = [list(map(int, r.split())) for r in L.ans('mask').split('\n')]
assert all(n % 3271 == 0 and n // 3271 == q and str(n).startswith('12') and str(n)[3:5] == '45' and str(n)[-1] == '6' and n < 10 ** 9
           for n, q in rows) and 2 <= len(rows) <= 11
rows = [list(map(int, r.split())) for r in L.ans('fast').split('\n')]
assert rows == [[n, n // 2023] for n in range(2023, 10 ** 10, 2023) if n % 10 == 4 and fnmatch(str(n), '1?2139*4')] and 2 <= len(rows) <= 11
