def run_ref(code, stdin):
    """Выполнить эталон (наш код из этого файла) на входных данных и вернуть вывод."""
    out = io.StringIO()
    old_in = sys.stdin
    try:
        sys.stdin = io.StringIO(stdin)
        with contextlib.redirect_stdout(out):
            exec(compile(code, "<buglab-ref>", "exec"), {"__name__": "__main__"})
    finally:
        sys.stdin = old_in
    return out.getvalue()


def norm(text):
    """Вывод сравнивается по словам: лишние пробелы и переводы строк не считаются ошибкой."""
    return str(text or "").split()


