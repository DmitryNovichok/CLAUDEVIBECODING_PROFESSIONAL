def changed_lines(case, code):
    """Сколько строк исходного решения ученик изменил, добавил или убрал (пустые строки и пробелы справа не в счёт)."""
    clean = lambda text: [ln.rstrip() for ln in str(text).replace("\r\n", "\n").split("\n") if ln.strip()]
    a, b = clean(case["code"]), clean(code)
    n = 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag != "equal":
            n += max(i2 - i1, j2 - j1)
    return n


def public(case):
    """То, что видит ученик до решения: без эталона, без объяснения, ожидаемый вывод — только у открытых тестов."""
    tests = [{"in": x, "open": i < case["open"], **({"exp": case["expected"][i]} if i < case["open"] else {})}
             for i, x in enumerate(case["inputs"])]
    return {k: case[k] for k in ("id", "title", "level", "kind", "topic", "who", "stmt", "code", "hints", "bugs", "par")} | {"tests": tests}


def check(case, runs):
    """runs — выводы программы ученика по тестам: [{out, err, timeout}]. Возвращает вердикт по каждому тесту."""
    res = []
    for i, exp in enumerate(case["expected"]):
        r = runs[i] if i < len(runs) and isinstance(runs[i], dict) else {}
        ok = not r.get("err") and not r.get("timeout") and norm(r.get("out")) == norm(exp)
        item = {"ok": ok, "open": i < case["open"]}
        if item["open"]:
            item["exp"] = exp
        res.append(item)
    return res
